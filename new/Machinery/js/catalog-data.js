// Helper: Filter machines
function getMachines(filterOptions = {}) {
  return DALAL_MACHINES.filter(m => {
    // If a specific category is selected, category takes priority over section
    if (filterOptions.category) {
      if (m.category !== filterOptions.category) return false;
    } else if (filterOptions.section) {
      if (m.section !== filterOptions.section) return false;
    }
    if (filterOptions.location && !m.location.toLowerCase().includes(filterOptions.location.toLowerCase())) return false;
    if (filterOptions.query) {
      const q = filterOptions.query.toLowerCase();
      const match = m.name.toLowerCase().includes(q) ||
                    m.make.toLowerCase().includes(q) ||
                    m.model.toLowerCase().includes(q) ||
                    m.id.toLowerCase().includes(q) ||
                    (m.categoryName && m.categoryName.toLowerCase().includes(q));
      if (!match) return false;
    }
    return true;
  });
}
